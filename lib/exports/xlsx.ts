import "server-only"

import ExcelJS from "exceljs"

import { COMPANY_TIME_LABEL, shiftToCompanyTime } from "@/lib/company-time"
import type { ExportColumn, ExportRow } from "@/lib/exports/csv"
import type { ReportExportRow } from "@/lib/services/reports"

export type WorkbookMeta = {
  title: string
  subtitle?: string
  generatedBy: string
  generatedAt: Date
  filters?: Record<string, string | undefined>
}

type ColumnKey =
  | "recordNumber"
  | "recordDateOnly"
  | "branchName"
  | "branchCode"
  | "branchCity"
  | "branchCountry"
  | "region"
  | "categoryName"
  | "title"
  | "referenceNumber"
  | "status"
  | "submittedDate"
  | "approvedDate"
  | "createdByName"
  | "approvedByName"

const COLUMNS: Array<{
  header: string
  key: ColumnKey
  width: number
}> = [
  { header: "Record number", key: "recordNumber", width: 20 },
  { header: "Record date", key: "recordDateOnly", width: 13 },
  { header: "Branch", key: "branchName", width: 24 },
  { header: "Branch code", key: "branchCode", width: 13 },
  { header: "City", key: "branchCity", width: 16 },
  { header: "Country", key: "branchCountry", width: 16 },
  { header: "Region", key: "region", width: 18 },
  { header: "Category", key: "categoryName", width: 20 },
  { header: "Title", key: "title", width: 36 },
  { header: "Reference", key: "referenceNumber", width: 18 },
  { header: "Status", key: "status", width: 12 },
  { header: "Submitted", key: "submittedDate", width: 13 },
  { header: "Approved", key: "approvedDate", width: 13 },
  { header: "Created by", key: "createdByName", width: 20 },
  { header: "Approved by", key: "approvedByName", width: 20 },
]

function cellValue(row: ReportExportRow, key: ColumnKey): string | Date | null {
  switch (key) {
    case "branchName":
      return row.branch.name
    case "branchCode":
      return row.branch.code
    case "branchCity":
      return row.branch.city
    case "branchCountry":
      return row.branch.country
    case "region":
      return row.branch.region.name
    case "categoryName":
      return row.category.name
    case "createdByName":
      return row.createdBy.name
    case "approvedByName":
      return row.approvedBy?.name ?? ""
    case "recordDateOnly":
      return row.recordDate
    case "submittedDate":
      return row.submittedAt ?? null
    case "approvedDate":
      return row.approvedAt ?? null
    case "recordNumber":
    case "title":
    case "referenceNumber":
    case "status":
      return row[key] ?? ""
    default:
      return null
  }
}

export async function buildReportXlsx(
  rows: ReportExportRow[],
  meta: WorkbookMeta
): Promise<Uint8Array> {
  const workbook = new ExcelJS.Workbook()
  workbook.creator = "Dana Company Operations Data"
  workbook.created = meta.generatedAt
  workbook.modified = meta.generatedAt
  workbook.subject = meta.title

  const sheet = workbook.addWorksheet("Records", {
    views: [{ state: "frozen", ySplit: 1 }],
  })

  const headers = COLUMNS.map((column) => column.header)
  sheet.columns = COLUMNS.map((column) => ({
    header: column.header,
    key: column.key,
    width: column.width,
  }))

  const headerRow = sheet.getRow(1)
  headerRow.height = 22
  headerRow.eachCell((cell) => {
    cell.font = { bold: true, color: { argb: "FFFFFFFF" }, size: 10, name: "Calibri" }
    cell.fill = {
      type: "pattern",
      pattern: "solid",
      fgColor: { argb: "FF1F3A44" },
    }
    cell.alignment = { vertical: "middle", horizontal: "left" }
    cell.border = {
      bottom: { style: "thin", color: { argb: "FFB8C4C7" } },
    }
  })

  rows.forEach((row) => {
    const values = Object.fromEntries(
      COLUMNS.map((column) => [column.key, cellValue(row, column.key)])
    )
    const added = sheet.addRow(values)
    added.height = 18
    added.eachCell((cell, colNumber) => {
      const column = COLUMNS[colNumber - 1]
      cell.font = { size: 9, name: "Calibri" }
      cell.alignment = { vertical: "middle", wrapText: column?.key === "title" }
      if (column?.key === "recordDateOnly" || column?.key === "submittedDate" || column?.key === "approvedDate") {
        cell.numFmt = "yyyy-mm-dd"
      }
    })
  })

  if (rows.length > 0) {
    sheet.autoFilter = {
      from: { row: 1, column: 1 },
      to: { row: 1, column: headers.length },
    }
  }

  const summary = workbook.addWorksheet("Report info")
  summary.columns = [{ width: 28 }, { width: 60 }]
  const infoRows: Array<[string, string]> = [
    ["Report", meta.title],
    ["Generated by", meta.generatedBy],
    [
      `Generated at (${COMPANY_TIME_LABEL})`,
      shiftToCompanyTime(meta.generatedAt)
        .toISOString()
        .replace("T", " ")
        .slice(0, 19),
    ],
    ["Records", String(rows.length)],
  ]

  if (meta.filters) {
    for (const [key, value] of Object.entries(meta.filters)) {
      if (value) infoRows.push([key, value])
    }
  }

  infoRows.forEach(([label, value]) => {
    const row = summary.addRow([label, value])
    row.getCell(1).font = { bold: true, size: 10, name: "Calibri" }
    row.getCell(2).font = { size: 10, name: "Calibri" }
  })

  summary.getRow(1).getCell(1).alignment = { vertical: "top" }

  const buffer = await workbook.xlsx.writeBuffer()
  return new Uint8Array(buffer)
}

export function defaultExportFilename(extension: string, at = new Date()): string {
  const shifted = shiftToCompanyTime(at)
  const stamp = `${shifted.getUTCFullYear()}${String(
    shifted.getUTCMonth() + 1
  ).padStart(2, "0")}${String(shifted.getUTCDate()).padStart(2, "0")}-${String(
    shifted.getUTCHours()
  ).padStart(2, "0")}${String(shifted.getUTCMinutes()).padStart(2, "0")}`
  return `dana-records-${stamp}.${extension}`
}

/**
 * Build a generic .xlsx workbook for any table. The first row is a styled,
 * frozen, filterable header; widths are sampled from the content.
 */
export async function toXlsx(
  title: string,
  columns: readonly ExportColumn[],
  rows: readonly ExportRow[]
): Promise<Uint8Array> {
  const workbook = new ExcelJS.Workbook()
  workbook.creator = "Records export"
  workbook.lastModifiedBy = "Records export"
  workbook.created = new Date()
  workbook.modified = new Date()

  const worksheet = workbook.addWorksheet(genericSheetName(title))

  if (columns.length === 0) {
    worksheet.getCell("A1").value = "No columns to export."
    const empty = await workbook.xlsx.writeBuffer()
    return new Uint8Array(empty as ArrayBuffer)
  }

  worksheet.columns = columns.map((column) => ({
    header: column.label,
    width: genericColumnWidth(column, rows),
  }))

  worksheet.addRows(
    rows.map((row) => columns.map((column) => row[column.key] ?? ""))
  )

  const header = worksheet.getRow(1)
  header.height = 20
  header.font = { bold: true, color: { argb: "FFFFFFFF" } }
  header.alignment = { vertical: "middle" }
  header.eachCell((cell) => {
    cell.fill = {
      type: "pattern",
      pattern: "solid",
      fgColor: { argb: "FF1F2937" },
    }
  })

  worksheet.views = [{ state: "frozen", ySplit: 1 }]
  worksheet.autoFilter = {
    from: { row: 1, column: 1 },
    to: { row: 1, column: columns.length },
  }

  const buffer = await workbook.xlsx.writeBuffer()
  return new Uint8Array(buffer as ArrayBuffer)
}

function genericColumnWidth(
  column: ExportColumn,
  rows: readonly ExportRow[]
): number {
  let longest = column.label.length
  const sampleSize = Math.min(rows.length, 200)

  for (let index = 0; index < sampleSize; index += 1) {
    const value = rows[index][column.key]
    if (value === null || value === undefined) continue
    longest = Math.max(longest, String(value).length)
  }

  return Math.min(50, Math.max(10, longest + 2))
}

function genericSheetName(title: string): string {
  const cleaned = title
    .replace(/[\\/?*[\]:]/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, 31)

  return cleaned || "Export"
}
